<h4 id="CulturalVariationsInLaw">Cultural and Regional Variations in Law</h4>
<p>
    Different societies emphasize vastly different moral priorities, reflected directly in how their legal codes function:
</p>
<ul>
    <li><strong>Feudal Monarchies &amp; Chivalric Realms:</strong> Heavy emphasis on sworn oaths, social hierarchy, and loyalty to the crown. Nobles enjoy broad legal exemptions and peer trials; treason, poaching in the king's forest, and counterfeiting royal currency bring swift, gruesome executions.</li>
    <li><strong>Merchant Republics &amp; Free Cities:</strong> Law is codified around contracts, property ownership, maritime shipping, and guild monopolies. Sentences focus heavily on monetary fines, restitution, asset seizure, commercial trade bans, and indenture rather than noble pardons.</li>
    <li><strong>Theocracies &amp; Inquisitorial States:</strong> Divine law and ecclesiastical courts take precedence over secular law. Heresy, apostasy, blasphemy, dark sorcery, and demon worship carry the harshest penalties (burning at the stake, soul cleansing, and excommunication), while divination magic is heavily used to inspect suspects' souls.</li>
    <li><strong>Dwarven Mountain Holds:</strong> Law is rooted in ancestral honor, clan solidarity, and strict contracts inscribed on stone tablets. Clan elders hold collective responsibility for an individual's offenses; punishments emphasize massive wergild fines, public loss of clan beard/crest, and permanent clan exile (viewed as a fate worse than death).</li>
    <li><strong>Elven Sanctuaries:</strong> Justice focuses on restorative harmony, nature balance, and moral reflection. Crude physical mutilation and gaols are rare; elven courts prefer magical <em>geas</em> penance, century-long banishment, or meditative isolation within enchanted glades.</li>
    <li><strong>Wilderness Frontiers &amp; Border Marches:</strong> Formal courts and magistrates are virtually nonexistent. Law is dispensed as "frontier justice" by local sheriffs, military march-wardens, or armed vigilante posses, relying on quick hanging trees, bounty boards, or outlaw declarations.</li>
</ul>

<h4 id="GMCrimeGuidance">GM Guidance: Running Crime and Justice in Campaigns</h4>
<p>
    When characters clash with the law—or investigate crimes on behalf of local authorities—GMs can use the following principles to enhance drama and roleplaying:
</p>
<ul>
    <li><strong>The Law as a Dynamic Force:</strong> Law enforcement should feel like a living part of the setting rather than an arbitrary wall. A party's <a href="#Reputation">Reputation</a>, <a href="#SocialClass">Social Class</a>, and faction <a href="#Influence">Influence</a> can open doors to royal pardons, bail agreements, or reduced sentencing, or conversely make local magistrates eager to make an example of them.</li>
    <li><strong>Bounties &amp; Outlaw Hunting:</strong> Declaring a villain (or a rogue PC) an outlaw introduces instant sandbox gameplay. Adventurers can hunt wanted fugitives across wilderness hexes, collect guild bounties, or navigate the underworld to clear their own framed names.</li>
    <li><strong>Quest Alternatives to Imprisonment:</strong> Rather than derailing a campaign with long dungeon gaol terms, wise magistrates frequently sentence capable adventurers to high-risk <em>penitence quests</em>—clearing an infested dungeon, retrieving a lost artifact, or defending a remote outpost—binding them with magical <em>geas</em> spells or sworn holy oaths.</li>
</ul>

<h3 id="Trading">Trading and Economy</h3>
<p>
    In most civilized lands, trade is regulated by municipal authorities, merchant syndicates, and craft guilds. Standardized coinage and precious metal bullion possess fixed, legally enforced exchange values. Gemstones, art objects, and bulk trade commodities (grain, timber, iron) also have established market values, leaving little room for price fluctuation in peaceful times.
</p>
<p>
    Manufactured goods, weapons, and armor vary significantly in craftsmanship, durability, and availability:
</p>
<ul>
    <li><strong>Retail Price:</strong> The listed price in the <a href="/reference/equipment">equipment lists</a> represents the standard retail cost to purchase an item in good condition from an established merchant or artisan.</li>
    <li><strong>Resale Value:</strong> When adventurers or non-merchants sell recovered equipment, weapons, or gear, merchants typically offer no more than <strong>50%</strong> of the listed retail price (accounting for merchant profit margins, refurbishment, and holding costs).</li>
    <li><strong>Black Market Rates:</strong> Underground syndicates and fences deal in contraband, forbidden sorcery, and stolen goods. Due to severe legal risks and smuggling overhead, buying through a black market costs <strong>200%</strong> of listed value, while selling illicit loot yields no more than <strong>25%</strong> of listed value.</li>
    <li><strong>Renting &amp; Leasing:</strong> Characters can lease specialized tools, mounts, or equipment for short expeditions. The standard rental fee is <strong>5% of the item's listed price per day</strong>, with additional security deposits required for high-risk ventures.</li>
</ul>

<h4>Coins and Currency</h4>
<p>
    Standard currency in RoL d20 is minted in uniform discs approximately 3 to 4 cm in diameter, weighing 10 g each (50 coins per 0.5 kg, or 100 coins per kilogram):
</p>
<ul>
    <li><strong>Copper Piece (cp):</strong> The standard coin of day-to-day subsistence and common laborers. <code>10 cp = 1 sp</code>.</li>
    <li><strong>Silver Piece (sp):</strong> The primary coin of common commerce. <code>10 sp = 1 gp</code>. As a benchmark, 1 sp possesses purchasing power roughly equivalent to $10 USD (year 2000 value).</li>
    <li><strong>Gold Piece (gp):</strong> The universal standard for adventurers, merchants, and landowners. <code>10 gp = 1 pp</code>.</li>
    <li><strong>Platinum Piece (pp):</strong> The rarest common coin, found predominantly in royal treasuries and ancient hoard vaults. <code>1 pp = 10 gp = 100 sp = 1,000 cp</code>.</li>
</ul>
<p>
    For large transactions, merchants and trade caravans utilize standardized <strong>Trade Bars</strong> of pure silver or gold, minted in 0.5 kg, 1 kg, 2.5 kg, and 5 kg ingots. Consult the trade goods tables for exact weight-to-value conversion ratios.
</p>

<h4>Banking and Moneychangers</h4>
<p>
    Almost every established town hosts one or more moneychangers who convert foreign coinages, weigh bullion bars, and authenticate precious metals for a standard transaction fee (typically 1% to 5%).
</p>
<p>
    Major commercial cities support established merchant banks offering sophisticated financial instruments:
</p>
<ul>
    <li><strong>Secure Vault Storage:</strong> Guarded safekeeping of coin reserves, deeds, and precious heirlooms.</li>
    <li><strong>Letters of Credit &amp; Money Transfers:</strong> Safe transmission of funds across kingdoms via recognized banking branches, eliminating the hazard of transporting physical bullion across bandit-ridden roads.</li>
    <li><strong>Commercial Loans &amp; Venture Financing:</strong> Lending capital for trade expeditions, ship construction, and civic infrastructure at interest.</li>
</ul>

<h4>Trade Fairs</h4>
<p>
    Civilized realms hold seasonal trade fairs where regional guilds, traveling caravans, foreign merchants, and local artisans gather for one to two weeks of intensive commerce. Fairs serve as massive cultural festivals featuring tourneys, bards, street performers, and food markets, while also attracting pickpockets, fences, and spies.
</p>

<h3 id="Religion">Religion</h3>
<p>
    Religion permeates almost every facet of daily life in fantasy worlds. The gods are not distant abstractions; their power manifests tangibly through miraculous spells, celestial visitations, divine smiting, and celestial and fiendish incursions. Temples serve as spiritual centers, communal sanctuaries, repositories of healing arts, and powerful political institutions that shape law, morality, and culture.
</p>

<h4 id="Deities">Deities and Pantheons</h4>
<p>
    Most civilizations revere pantheons of deities representing diverse aspects of existence—from creation, war, and justice to harvest, commerce, storms, and death. Rather than worshipping a single god exclusively, common folk offer prayers and tithes to whichever deity oversees their immediate circumstances, such as entreating the goddess of healing during sickness or praying to the god of the sea before a voyage.
</p>
<p>
    Deities are classified by their cosmic potency and planar authority into four primary divine ranks:
</p>
<ul>
    <li><strong>Greater Deities (Rank G):</strong> Immortal primordial rulers and cosmic creators who command vast planar dominions and multitudes of worshippers. They can reshape realities, grant spells across all planes, and rarely manifest directly in mortal realms without risking cosmic cataclysms.</li>
    <li><strong>Intermediate Deities (Rank I):</strong> Major gods presiding over key portfolios such as agriculture, battle, crafts, or the dead. They actively guide mortal churches and champion planar crusades.</li>
    <li><strong>Lesser Deities (Rank L):</strong> Specialized divine patrons governing narrower portfolios, specific races, geographic regions, or unique crafts.</li>
    <li><strong>Demigods &amp; Quasi-Deities (Rank D):</strong> Ascended mortal heroes, divine offspring, or immortal guardians who possess extraordinary divine power and can grant limited spells to small cults or sworn champions.</li>
</ul>

<h5>Clerical Devotion &amp; Divine Mechanics</h5>
<p>
    While lay worshippers venerate entire pantheons, clerics, paladins, and divine champions forge a dedicated covenant with a specific patron deity:
</p>
<ul>
    <li><strong>Alignment Harmony:</strong> A cleric's alignment must generally remain within one step of their deity's alignment (e.g., a Lawful Good deity accepts Lawful Good, Neutral Good, or Lawful Neutral clerics) and can never be opposed on either the Law/Chaos or Good/Evil axis.</li>
    <li><strong>Affinity Domains:</strong> Each deity grants access to specific divine domains (such as <em>Sun</em>, <em>War</em>, <em>Healing</em>, <em>Knowledge</em>, <em>Protection</em>, <em>Magic</em>, or <em>Trickery</em>). A cleric chooses domains granted by their patron, unlocking domain affinity skills, bonus spell repertoires, and specialized channeling traits.</li>
    <li><strong>Favored Weapons:</strong> Every deity sanctifies a specific favored weapon (such as the warhammer for Moradin, the longsword for Heironeous, or the bow for Corellon Larethian). Clerics gain martial familiarity and divine bonuses when wielding their patron's consecrated armament.</li>
    <li><strong>Holy Symbols &amp; Divine Foci:</strong> Priesthoods channel divine energy through consecrated holy symbols carved from silver, wood, or sacred stone. A holy symbol serves as an indispensable divine focus implement for manifesting spells and turning or rebuking planar creatures.</li>
</ul>

