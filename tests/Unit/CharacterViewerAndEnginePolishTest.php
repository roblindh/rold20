<?php
declare(strict_types=1);

namespace Tests\Unit;

use Tests\TestCase;
use App\Services\Entity\EntityEngine;
use App\Services\Entity\EquipmentManager;
use App\Services\Entity\TraitEvaluator;
use App\Services\Entity\ModifierStackingEngine;

class CharacterViewerAndEnginePolishTest extends TestCase
{
    public function testArmorRegistersDrDeCAndEC(): void
    {
        $engine = new ModifierStackingEngine();
        $context = ['lvl' => 1];

        // Armor trait
        $traits = TraitEvaluator::parse('Armor { Category=ArmHv; DR=8; DeC=-2; EC=4; }');
        TraitEvaluator::applyTraitsToEngine($traits, $engine, $context, 'Full plate', 'wearer');

        $this->assertEquals(8, $engine->getTotal('DR'));
        $this->assertEquals(-2, $engine->getTotal('DeC'));
        $this->assertEquals(4, $engine->getTotal('EC'));
    }

    public function testSpeedFormattingWithClimbAndSwimMultipliers(): void
    {
        $entity = [
            'Name' => 'Lizardfolk Champion',
            'BaseRace' => 1,
            'Classes' => [4],
            'BaseStr' => 14,
            'BaseDex' => 12,
            'BaseCon' => 14,
            'BaseInt' => 10,
            'BaseWis' => 10,
            'BaseCha' => 10,
        ];

        $calc = EntityEngine::calculate($entity);
        $this->assertArrayHasKey('speeds', $calc);
        $this->assertArrayHasKey('display', $calc['speeds']);
        $this->assertStringContainsString('sq Ground', $calc['speeds']['display']);
        $this->assertStringContainsString('Climb ×', $calc['speeds']['display']);
        $this->assertStringNotContainsString('Climb', $calc['traits']['movement_str'] ?? '');
    }

    public function testEquippedAndCarriedWeaponsIncluded(): void
    {
